from __future__ import annotations


MAX_DETAIL = 500


def _option(option_id, label, detail, impact, route_note, *, action="continue"):
    return {
        "id": option_id, "label": label, "detail": detail,
        "impact": impact, "route_note": route_note, "action": action,
    }


def _question(question_id, context, signals, question, why, options, *, placeholder=None):
    return {
        "status": "question", "id": question_id, "context": context,
        "signals": [{"label": label, "value": value} for label, value in signals],
        "question": question, "why": why, "options": options,
        "placeholder": placeholder or "Если хотите, добавьте одну важную деталь…",
    }


