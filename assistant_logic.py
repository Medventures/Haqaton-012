def build_clarification(answers: dict) -> dict:
    """Return one reproducible question without exposing internal plan actions."""
    question = _select_question(answers)
    question["options"] = [
        {key: option[key] for key in ("id", "label", "detail")}
        for option in question["options"]
    ]
    return question


def resolve_clarification(answers: dict, answer: dict) -> dict:
    """Recompute the question and turn a validated answer into a handoff note."""
    question = _select_question(answers)
    if not isinstance(answer, dict):
        raise ValueError("Проверьте ответ на уточняющий вопрос.")
    if answer.get("question_id") != question["id"]:
        raise ValueError("Анкета изменилась. Получите новый уточняющий вопрос.")
    detail = answer.get("detail", "")
    if not isinstance(detail, str) or len(detail) > MAX_DETAIL:
        raise ValueError("Уточнение должно быть не длиннее 500 символов.")
    detail = detail.strip()
    skipped = answer.get("skipped", False)
    if not isinstance(skipped, bool):
        raise ValueError("Проверьте ответ на уточняющий вопрос.")
    option_id = answer.get("option_id")
    if skipped and option_id not in (None, ""):
        raise ValueError("Выберите ответ или пропустите уточнение.")
    if skipped:
        label = "Уточнение пропущено"
        impact = "План составлен по исходной анкете. Этот вопрос можно обсудить с врачом на приёме."
        route_note = "Уточнение пока без ответа: " + question["question"]
        action = "continue"
    else:
        option = next((item for item in question["options"] if item["id"] == option_id), None)
        if option is None:
            raise ValueError("Выберите один из ответов или пропустите уточнение.")
        label, impact = option["label"], option["impact"]
        route_note, action = option["route_note"], option["action"]
    clinician_note = f"Вопрос: {question['question']} Ответ: {label}."
    if detail:
        clinician_note += f" Дополнение пациента: {detail}"
    return {
        "question_id": question["id"], "question": question["question"],
        "answer_label": label, "detail": detail, "skipped": skipped,
        "impact_title": "Уточнение можно обсудить на приёме" if skipped else (
            "Сначала нужна медицинская помощь" if action == "urgent" else
            "Сначала обсудите это с врачом" if action == "consultation" else
            "Одна деталь — более точный план"
        ),
        "impact": impact, "clinician_note": clinician_note,
        "route_note": route_note, "action": action,
    }
